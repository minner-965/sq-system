-- 互动收件箱：补充兜底关键词。
-- 用 46 条贴近真实的评论和私信自测，发现只靠关键词会漏掉一半左右的意向评论。
-- 现在有大模型时每条都交给模型判断；关键词只在模型不可用时兜底，这里把自测中漏掉的说法补上。
UPDATE leadgen.inbox_settings
SET intent_keywords = (
        SELECT array_agg(DISTINCT keyword) FROM unnest(intent_keywords || ARRAY[
            '明火', '餐饮', '报价', '押几', '付几', '押金', '注册', '停车', '车位', '月卡', '签多久', '起租', '家具', '地铁',
            '怎么过去', '怎么走', '资料', '带看', '实地', '上门', '约个', '约时间', '过来', '进驻', '对接', '带客', '佣金',
            '有房', '大床', '双床', '什么价', '啥价', '团建', '安排', '收费', '几个人', '多大', '物业', '含税', '优惠'
        ]) AS keyword),
    updated_at = now()
WHERE id = 1;
